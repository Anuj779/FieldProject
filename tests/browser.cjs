// Run with NODE_PATH pointing to an installed Playwright package, or the bundled runtime.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  fs.mkdirSync('test-results', {recursive: true});
  const browser = await chromium.launch({headless: true});
  const page = await browser.newPage({viewport: {width: 1440, height: 1000}, reducedMotion: 'reduce'});
  const errors = [];
  // Keep interface checks deterministic regardless of local Firebase credentials.
  await page.route('**/api/config', route => route.fulfill({json: {firebase: null, ai_ready: true}}));
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:5000');
  await page.waitForFunction(() => window.Alpine && Alpine.$data(document.body).configLoaded);
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({path: 'test-results/home-desktop.png', fullPage: true});
  await page.getByRole('button', {name: 'Explore a sample'}).first().click();
  await page.locator('.finding').first().waitFor();
  assert.equal(await page.locator('.finding').count(), 6);
  await page.locator('#filter').selectOption('Penalty');
  await page.waitForFunction(() => document.querySelectorAll('.finding').length === 1);
  await page.getByText('Read original clause').click();
  assert.match(await page.locator('blockquote').innerText(), /INR 200/);
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', {name: 'Download report'}).click();
  const download = await downloadPromise;
  await download.saveAs('test-results/sample-report.pdf');
  assert.ok(fs.statSync('test-results/sample-report.pdf').size > 1000);
  await page.locator('#filter').selectOption('All');
  await page.screenshot({path: 'test-results/results-desktop.png', fullPage: true});
  await page.getByRole('button', {name: 'Sign in ↗', exact: true}).click();
  await page.locator('#email').fill('student@example.com');
  await page.getByRole('button', {name: 'Forgot password?'}).click();
  assert.equal(await page.getByRole('heading', {name: 'Reset your password.'}).count(), 1);
  await page.locator('.auth-switch button').click();
  await page.locator('.auth-switch button').click();
  assert.equal(await page.getByRole('heading', {name: 'Create your account.'}).count(), 1);
  assert.equal(await page.locator('button[type=submit]').isDisabled(), true);
  await page.screenshot({path: 'test-results/login-desktop.png', fullPage: true});
  // Layout check of the protected upload view without making a live request.
  await page.evaluate(() => { const state = Alpine.$data(document.body); state.user={email:'layout-test@example.com'}; state.go('workspace'); });
  await page.locator('#pdf-file').setInputFiles({name: 'invalid.txt', mimeType: 'text/plain', buffer: Buffer.from('not pdf')});
  assert.match(await page.locator('.upload-panel [role=alert]').innerText(), /PDF file/);
  await page.locator('#pdf-file').setInputFiles('output/pdf/Clausewise-Sample-Agreement.pdf');
  await page.waitForFunction(() => Alpine.$data(document.body).file?.name === 'Clausewise-Sample-Agreement.pdf');
  assert.equal(await page.getByRole('button', {name: 'Analyze agreement'}).isDisabled(), true);
  await page.locator('.consent input').check();
  assert.equal(await page.getByRole('button', {name: 'Analyze agreement'}).isEnabled(), true);
  await page.screenshot({path:'test-results/upload-desktop.png', fullPage:true});
  await page.goto('http://127.0.0.1:5000');
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(() => Alpine.$data(document.body).configLoaded);
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({path:'test-results/home-mobile.png',fullPage:true});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.getByRole('button',{name:'Explore a sample'}).first().click();
  await page.locator('.finding').first().waitFor();
  await page.screenshot({path:'test-results/results-mobile.png',fullPage:true});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.getByRole('button',{name:'Sign in ↗',exact:true}).click();
  await page.locator('.auth-panel').waitFor({state:'visible'});
  await page.waitForFunction(() => document.documentElement.scrollHeight < 1500);
  await page.screenshot({path:'test-results/login-mobile.png',fullPage:true});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('Browser checks passed: sample, filtering, source expansion, PDF download, login modes, invalid upload, mobile overflow, and no JS errors.');
})().catch(error => {console.error(error);process.exit(1);});
